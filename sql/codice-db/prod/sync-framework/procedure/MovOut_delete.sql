CREATE PROCEDURE [MovOut_delete]
	@P_19 UniqueIdentifier,
	@sync_force_write Int,
	@sync_min_timestamp BigInt,
	@sync_row_count Int OUTPUT
AS
BEGIN
SET @sync_row_count = 0; DELETE [MovOut] FROM [MovOut] [base] JOIN [MovOut_tracking] [side] ON [base].[Keys] = [side].[Keys] WHERE ([side].[local_update_peer_timestamp] <= @sync_min_timestamp OR @sync_force_write = 1) AND ([base].[Keys] = @P_19); SET @sync_row_count = @@ROWCOUNT;
END
